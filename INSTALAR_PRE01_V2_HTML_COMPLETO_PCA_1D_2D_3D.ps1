Write-Host "PCA 1D / 2D / 3D | K=$K | n_init=$NInit | tipo=$Tipo" -ForegroundColor Cyan
Write-Host 'F1-F9 apenas; nao recalcula GMM nem OOF.' -ForegroundColor Cyan

# Start-Process isola stderr: alertas de fonte nao sao erros do PowerShell.
# Quote obrigatorio pois o caminho do projeto contem espacos.
$argumentos="-u -m src.pre01_v2_diagnostico --raiz `"$raiz`" --k $K --n-init $NInit --tipo $Tipo"
$processo=Start-Process -FilePath $python -ArgumentList $argumentos -WorkingDirectory $raiz -NoNewWindow -Wait -PassThru -RedirectStandardOutput $logOut -RedirectStandardError $logErr
if (Test-Path $logOut) {
    $texto=Get-Content -LiteralPath $logOut -Raw -Encoding UTF8
    Write-Host $texto
} else { $texto='' }
if ($processo.ExitCode -ne 0) {
    Write-Host "[FALHA] Codigo do Python: $($processo.ExitCode)" -ForegroundColor Red
    if (Test-Path $logErr) {Get-Content -LiteralPath $logErr -Tail 80 -Encoding UTF8 | Out-Host}
    throw 'PRE01 V2 falhou. Dados/OOF preservados. Verifique o traceback acima.'
}
if (Test-Path $logErr) {
    $erros=Get-Content -LiteralPath $logErr -Raw -Encoding UTF8
    if (-not [string]::IsNullOrWhiteSpace($erros)) {Write-Host "[AVISOS PYTHON] $logErr" -ForegroundColor Yellow}
}
$match=[regex]::Match($texto,'(?m)^PAINEL=(.+)$')
if (-not $match.Success) {throw 'Execucao terminou, mas caminho PAINEL nao foi localizado no log.'}
$painel=$match.Groups[1].Value.Trim()
if (-not (Test-Path -LiteralPath $painel -PathType Leaf)) {throw "HTML do painel nao encontrado: $painel"}
Write-Host "[SUCESSO] HTML interativo: $painel" -ForegroundColor Green
try {
    Start-Process -FilePath $painel -ErrorAction Stop
    Write-Host '[NAVEGADOR] Abertura solicitada ao Windows.' -ForegroundColor Green
} catch {
    Write-Host '[NAVEGADOR] Abertura automatica indisponivel; abra o HTML pelo caminho acima.' -ForegroundColor Yellow
}
